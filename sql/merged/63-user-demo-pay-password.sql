-- =====================================================================
-- 63-user-demo-pay-password.sql
-- 演示账号 Jack 的口令预置（支付口令 888888 + 登录口令 123456）—— 仅演示 / 冒烟环境
--
-- ============================ 一、本脚本做什么 ============================
-- 把演示账号 Jack 的两个口令列收敛成"冒烟脚本能直接用的状态"：
--   1) llmall-user.user.pay_password：从 60 号脚本写入的"初始支付口令 123456 的哈希"
--      改成"888888 的哈希"，使该账号处于"已经改过一次支付密码"的状态；
--   2) llmall-user.user.password：从 sql/llmall-user.sql（原商城导出）里那条**原商城口令**的哈希
--      改成"123456 的哈希"，使 MallE2E 硬编码的 Jack/123456 登录步可用。
-- 不新增列、不改表结构；两条 UPDATE 都只命中"仍是某个已知旧值"的行。
--
-- 【为什么两件事合成一个脚本】它们解决的是同一个问题：全新库里的演示账号**不可用于冒烟**。
-- 一个卡在登录（口令对不上），一个卡在扣款（被"首次支付前强制改密"拦下）。
-- 拆成两个脚本只会让人漏跑其中一个，症状还都表现为"冒烟莫名其妙红了"。
--
-- ============================ 二、为什么需要它（存在理由） ============================
-- 冒烟脚本 scripts/MallE2E.java 的第一步是 Jack/123456 登录，随后走到余额支付：
-- 登录 → 下单 → 申请支付单 → 用支付口令扣款。两处都会被全新库的默认值卡住：
-- 余额支付链路上有一条防资损拦截（llmall-user-service 的 UserServiceImpl#deductMoney）：
--     当前 pay_password 与初始口令 123456 相匹配 → 拒绝扣款，
--     提示"请先修改支付密码（当前仍为初始密码），修改后再进行余额支付"。
-- 60 号脚本把存量账号的 pay_password 统一置为初始口令的哈希，于是全新库里 Jack 恒处于
-- "从未改过支付口令"的状态，冒烟必然卡在扣款这一步；
-- 而改密接口 POST /users/pay-password 要求短信验证码，冒烟脚本无法自给，也不该为此在服务端开后门。
-- 所以把演示账号的支付口令预置成 888888 的哈希，让冒烟走"这个账号已经改过支付密码"的正常路径。
--
-- 【安全语义不变】被绕开的只是"演示账号从未改过支付密码"这一个状态，不是那条拦截本身：
--   拦截仍按"当前口令是否等于初始口令"判断，任何仍在使用初始口令的账号照样被拦下。
--
-- 登录这一处：sql/llmall-user.sql 是原商城导出，Jack 的 password 对应**原商城口令**而非 123456。
--
-- ============================ 三、适用范围（重要） ============================
-- 本脚本是**演示 / 冒烟专用**：它把账号的支付口令改成公开可知的值（888888）、
-- 登录口令改成 MallE2E 硬编码的 123456。
-- 生产库与任何对外开放的库**不得执行**；只有演示库、冒烟库、从零重建的容器库才需要它。
--
-- ============================ 四、幂等性 ============================
-- 两条 UPDATE 都带"只命中已知旧值"的 WHERE：
--   支付口令段：限定 username = 'Jack' 且 pay_password 仍是 60 号写入的初始口令哈希；
--   登录口令段：限定 username = 'Jack' 且 password 仍是原商城导出那条哈希；
--   · 第二遍执行两条都命中 0 行；
--   · 账号若已自行改过口令（既不是旧值也不是目标值），不会被覆盖。
-- 列不存在时（未执行 60 号）不报错，只打印一句提示后跳过，与 60 号同一套 information_schema 守卫写法。
--
-- ============================ 五、前置依赖与执行位置 ============================
-- 依赖 60-user-pay-password.sql（pay_password 列）与演示数据里的 Jack 这一行。
-- 在 seed 链里排在 60 号之后、应用启动之前；demo.ps1 的 SQL 清单已按此顺序登记本脚本。
--
-- ============================ 六、校验 ============================
-- 末尾输出 Jack 的口令指纹（前 7 位 / 长度 / 是否为 888888 的哈希 / 是否仍为初始哈希 / 是否123456的哈希）。
-- 期望：哈希长度 60、是否888888的哈希 = 1、是否仍为初始哈希 = 0、是否123456的哈希 = 1。
-- 888888 的哈希由本项目的 BCryptPasswordEncoder 生成并比对通过；
-- 初始口令的哈希取自 60 号脚本（两者都是同一套 encoder 的产物）。
--
-- ============================ 七、风险等级 ============================
-- 低（仅演示环境）—— 单表单列单行 UPDATE，可重复执行，不动表结构、不动登录凭据。
--
-- 执行：mysql -uroot -p123 llmall-user < 63-user-demo-pay-password.sql
-- =====================================================================

-- ---------------------------------------------------------------------
-- 列不存在时只打印提示：全新库若漏跑 60 号，本脚本不该以报错的形式失败
-- （报错会掩盖真正的问题：60 号没进 seed 链），也不该静默地把状态改坏。
-- ---------------------------------------------------------------------
SET @c := (SELECT COUNT(*) FROM information_schema.COLUMNS
           WHERE TABLE_SCHEMA = 'llmall-user' AND TABLE_NAME = 'user'
             AND COLUMN_NAME = 'pay_password');
SET @s := IF(@c = 0,
    'SELECT ''llmall-user.user.pay_password 列不存在：跳过 63 号（请先执行 60-user-pay-password.sql）''',
    'UPDATE `llmall-user`.`user`
        SET `pay_password` = ''$2a$10$w8OQd1hDI4hFoiz8U7z5uu52DgG8CE2HPPvmq/j8C1yW9UTRvAPai''
      WHERE `username` = ''Jack''
        AND `pay_password` = ''$2a$10$n5qsrxCUqQP.Asc6LFPNruxdxOr1bARG4tEyX7iDWni6wQIu3R7HO''');
PREPARE st FROM @s; EXECUTE st; DEALLOCATE PREPARE st;

-- ---------------------------------------------------------------------
-- 登录口令：把演示账号的登录口令统一成 MallE2E 硬编码的那个 123456。
--
-- 为什么这件事也归本脚本管：全新库的 Jack 来自 sql/llmall-user.sql（原商城导出），
-- 那里的 password 哈希对应的是**原商城口令**，不是冒烟脚本用的 123456 ——
-- 于是 MallE2E 第一步"登录 Jack/123456"就会以「用户名或密码错误」失败，
-- 整套冒烟一个断言都跑不到。冒烟账号的口径必须由脚本落库，不能依赖"某台演示库被手工改过"。
--
-- 幂等：WHERE 只命中"仍是原商城导出那一条哈希"的行 ——
--   已是 123456 哈希的库（长期在用的演示库）命中 0 行，不会被重复改写；
--   已自行改过登录口令的账号（值既不是原导出哈希也不是目标哈希）不受影响。
-- ⛔ 与上面的支付口令一样，仅演示 / 冒烟环境适用，生产库不得执行。
-- ---------------------------------------------------------------------
UPDATE `llmall-user`.`user`
   SET `password` = '$2a$10$OZk7o1YZx8zKd15t7yIYaexCmWmRtIwsyV9nyL6Bp56qXcJSehlye'
 WHERE `username` = 'Jack'
   AND `password` = '$2a$10$6ptTq3V9XfaJmFYwYT2W9ud377BUkEWk.whf.iQ.0sX5F.L497rAC';

-- 校验：
--   哈希长度 = 60 且 是否888888的哈希 = 1 → 支付口令预置到位
--   是否仍为初始哈希 = 0                  → 不再被"首次支付前强制改密"拦下
--   是否123456的哈希 = 1                  → MallE2E 的登录步可用
--   第二遍执行时两段 UPDATE 都命中 0 行，本查询结果不变。
SELECT `username`                                   AS `账号`,
       LEFT(`pay_password`, 7)                      AS `哈希前缀`,
       LENGTH(`pay_password`)                       AS `哈希长度`,
       (`pay_password` = '$2a$10$w8OQd1hDI4hFoiz8U7z5uu52DgG8CE2HPPvmq/j8C1yW9UTRvAPai') AS `是否888888的哈希`,
       (`pay_password` = '$2a$10$n5qsrxCUqQP.Asc6LFPNruxdxOr1bARG4tEyX7iDWni6wQIu3R7HO') AS `是否仍为初始哈希`,
       (`password` = '$2a$10$OZk7o1YZx8zKd15t7yIYaexCmWmRtIwsyV9nyL6Bp56qXcJSehlye') AS `是否123456的哈希`
  FROM `llmall-user`.`user`
 WHERE `username` = 'Jack';
